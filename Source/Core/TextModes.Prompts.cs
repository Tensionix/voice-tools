    /// <summary>The dictionary of SETTINGS (Core\Vocabulary.cs) as the model is told it; "" - none.</summary>
    static string Dictionary(string root)
    {
        var entries = Vocabulary.Entries(root);
        var terms = entries.Where(one => one.Said.Length == 0).Select(one => one.Written).ToList();
        var replacements = entries.Where(one => one.Said.Length > 0).Select(one => $"«{one.Said}» - «{one.Written}»").ToList();
        var said = "";
        if (terms.Count > 0) said += "\n\nСловарь - эти термины, аббревиатуры, сокращения и единицы пиши точно так: " + string.Join("; ", terms) + ".";
        if (replacements.Count > 0) said += "\n\nЗамены - сказанное слева пиши так, как справа: " + string.Join("; ", replacements) + ".";
        return said;
    }

